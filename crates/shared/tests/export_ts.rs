use reclip_shared::tools::tool_defs;
use reclip_shared::*;
use ts_rs::{Config, TS};

const HEADER: &str = "// Generated by crates/shared/tests/export_ts.rs. Do not edit.\n";
const OUT: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../web/src/api/types.gen.ts"
);

const TOOLS_OUT: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../web/src/api/tools.gen.json"
);

fn decl<T: TS>(cfg: &Config) -> String {
    format!("export {}\n", T::decl(cfg).trim())
}

fn generate() -> String {
    let cfg = Config::default();
    let mut out = String::from(HEADER);
    for d in [
        decl::<MediaFormat>(&cfg),
        decl::<Clip>(&cfg),
        decl::<JobState>(&cfg),
        decl::<ErrorCode>(&cfg),
        decl::<ApiError>(&cfg),
        decl::<FormatOption>(&cfg),
        decl::<VideoInfo>(&cfg),
        decl::<PlaylistEntry>(&cfg),
        decl::<PlaylistInfo>(&cfg),
        decl::<ProbeResponse>(&cfg),
        decl::<ProbeRequest>(&cfg),
        decl::<CreateJobRequest>(&cfg),
        decl::<Job>(&cfg),
        decl::<JobList>(&cfg),
        decl::<PublicLimits>(&cfg),
        decl::<PublicConfig>(&cfg),
        decl::<LinkResponse>(&cfg),
        decl::<Scope>(&cfg),
        decl::<KeyLimits>(&cfg),
        decl::<CreateKeyRequest>(&cfg),
        decl::<ApiKeyInfo>(&cfg),
        decl::<CreatedKey>(&cfg),
        decl::<ApiKeyList>(&cfg),
        decl::<AdminLogin>(&cfg),
        decl::<AdminMe>(&cfg),
        decl::<AdminPasswordChange>(&cfg),
        decl::<HistoryEntry>(&cfg),
        decl::<HistoryList>(&cfg),
        decl::<HistoryCleanMode>(&cfg),
        decl::<HistoryClean>(&cfg),
        decl::<HistoryCleanResult>(&cfg),
        decl::<TranscriptRequest>(&cfg),
        decl::<Transcript>(&cfg),
    ] {
        out.push('\n');
        out.push_str(&d);
    }
    out.replace("\r\n", "\n")
}

fn normalize(s: &str) -> String {
    s.replace("\r\n", "\n")
}

fn generate_tools() -> String {
    let mut json = serde_json::to_string_pretty(&tool_defs()).unwrap();
    json.push('\n');
    json
}

/// Compare `expected` with the file at `out`, or rewrite it under `UPDATE_TS=1`.
fn check_generated(out: &str, expected: &str, what: &str) {
    if std::env::var("UPDATE_TS").is_ok_and(|v| v == "1") {
        std::fs::create_dir_all(std::path::Path::new(out).parent().unwrap()).unwrap();
        std::fs::write(out, expected).unwrap();
        return;
    }
    let actual = std::fs::read_to_string(out)
        .unwrap_or_else(|_| panic!("{out} missing: run UPDATE_TS=1 cargo test -p reclip-shared"));
    assert_eq!(
        normalize(&actual),
        expected,
        "{what} is stale: run UPDATE_TS=1 cargo test -p reclip-shared"
    );
}

#[test]
fn types_gen_is_up_to_date() {
    check_generated(OUT, &generate(), "types.gen.ts");
}

#[test]
fn tools_json_is_up_to_date() {
    check_generated(TOOLS_OUT, &generate_tools(), "tools.gen.json");
}
