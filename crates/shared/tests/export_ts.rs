use reclip_shared::*;
use ts_rs::{Config, TS};

const HEADER: &str = "// Generated by crates/shared/tests/export_ts.rs. Do not edit.\n";
const OUT: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../web/src/api/types.gen.ts"
);

fn decl<T: TS>(cfg: &Config) -> String {
    format!("export {}\n", T::decl(cfg).trim())
}

fn generate() -> String {
    let cfg = Config::default();
    let mut out = String::from(HEADER);
    for d in [
        decl::<MediaFormat>(&cfg),
        decl::<JobState>(&cfg),
        decl::<ErrorCode>(&cfg),
        decl::<ApiError>(&cfg),
        decl::<FormatOption>(&cfg),
        decl::<VideoInfo>(&cfg),
        decl::<PlaylistInfo>(&cfg),
        decl::<ProbeResponse>(&cfg),
        decl::<ProbeRequest>(&cfg),
        decl::<CreateJobRequest>(&cfg),
        decl::<Job>(&cfg),
        decl::<PublicConfig>(&cfg),
    ] {
        out.push('\n');
        out.push_str(&d);
    }
    out.replace("\r\n", "\n")
}

fn normalize(s: &str) -> String {
    s.replace("\r\n", "\n")
}

#[test]
fn types_gen_is_up_to_date() {
    let expected = generate();
    if std::env::var("UPDATE_TS").is_ok_and(|v| v == "1") {
        std::fs::create_dir_all(std::path::Path::new(OUT).parent().unwrap()).unwrap();
        std::fs::write(OUT, expected).unwrap();
        return;
    }
    let actual = std::fs::read_to_string(OUT)
        .unwrap_or_else(|_| panic!("{OUT} missing: run UPDATE_TS=1 cargo test -p reclip-shared"));
    assert_eq!(
        normalize(&actual),
        expected,
        "types.gen.ts is stale: run UPDATE_TS=1 cargo test -p reclip-shared"
    );
}
